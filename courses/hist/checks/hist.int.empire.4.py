# checks/hist.int.empire.4.py: recomputes every number in the chapter (dates, intervals, ratios, totals)
from datetime import date
import re, os


def eq(label, got, want):
    assert got == want, f"{label}: computed {got}, chapter says {want}"


def between(label, x, lo, hi):
    assert lo <= x <= hi, f"{label}: {x} not in [{lo}, {hi}]"


# Frontier: census 1890, Turner 12 July 1893; Panic of 1893 to 1897
eq("census to Turner", 1893 - 1890, 3)
eq("depression years", 1897 - 1893, 4)
# Hawaii: overthrow 17 January 1893, annexation 7 July 1898 = five and a half years
between("Hawaii overthrow to annexation (years)", (date(1898, 7, 7) - date(1893, 1, 17)).days / 365.25, 5.4, 5.6)
# Maine: de Lome letter 9 February, Maine 15 February 1898 = six days; war declared 25 April
eq("de Lome to Maine (days)", (date(1898, 2, 15) - date(1898, 2, 9)).days, 6)
eq("Maine to McKinley message (days)", (date(1898, 4, 11) - date(1898, 2, 15)).days, 55)
eq("Maine to declaration (days)", (date(1898, 4, 25) - date(1898, 2, 15)).days, 69)
eq("Maine crew died fraction", round(260 / 355 * 100), 73)
# Spanish-American War: declaration 25 April to armistice 12 August 1898 = 109 days (about 16 weeks)
eq("war days", (date(1898, 8, 12) - date(1898, 4, 25)).days, 109)
# casualties: 369 soldiers + 10 sailors + 6 marines killed; 2,061 died of disease; total dead 2,446
eq("killed in action", 369 + 10 + 6, 385)
eq("total dead", 369 + 10 + 6 + 2061, 2446)
# Treaty of Paris signed 10 December 1898, ratified 6 February 1899 (57-27: two-thirds of 84 is 56)
eq("votes cast", 57 + 27, 84)
assert 57 >= -(-2 * 84 // 3), "57 is at least two thirds"
eq("two thirds of 84", 2 * 84 // 3, 56)
eq("Paris to ratification (days)", (date(1899, 2, 6) - date(1898, 12, 10)).days, 58)
eq("Philippine war began two days before Senate vote", (date(1899, 2, 6) - date(1899, 2, 4)).days, 2)
# Philippine war 4 February 1899 to 4 July 1902: 3 years 5 months
between("Philippine war years", (date(1902, 7, 4) - date(1899, 2, 4)).days / 365.25, 3.4, 3.5)
# Casualties: 1,020 killed + 3,176 disease = 4,196 ("over 4,000")
eq("US dead", 1020 + 3176, 4196)
assert 4196 > 4000
# Aguinaldo captured 23 March 1901; Balangiga 28 September 1901
assert date(1901, 3, 23) < date(1901, 9, 28)
# Fillmore etc not used. Panama: revolt 3 Nov 1903, recognised three days later, treaty 18 November
eq("recognition days", (date(1903, 11, 6) - date(1903, 11, 3)).days, 3)
eq("revolt to treaty (days)", (date(1903, 11, 18) - date(1903, 11, 3)).days, 15)
# Canal 1904-1914 (construction about a decade), opened 15 August 1914
eq("construction years", 1914 - 1904, 10)
# Roosevelt Corollary 1904, Dollar Diplomacy 1912
eq("Corollary to Taft message", 1912 - 1904, 8)
# Great White Fleet 16 December 1907 to 22 February 1909 = 14 months
d = (date(1909, 2, 22) - date(1907, 12, 16)).days
eq("fleet days", d, 434)
between("fleet months", d / 30.44, 14.1, 14.3)
# WWI: Lusitania 7 May 1915; Sussex 24 March 1916; pledge 4 May 1916 (a year less 3 days after Lusitania)
eq("Lusitania to Sussex pledge (days)", (date(1916, 5, 4) - date(1915, 5, 7)).days, 363)
eq("Sussex to pledge (days)", (date(1916, 5, 4) - date(1916, 3, 24)).days, 41)
# Announcement 31 Jan 1917, break 3 Feb: 3 days; telegram sent 16 Jan, published 1 March = 44 days
eq("announcement to break (days)", (date(1917, 2, 3) - date(1917, 1, 31)).days, 3)
eq("telegram sent to published (days)", (date(1917, 3, 1) - date(1917, 1, 16)).days, 44)
eq("telegram published to war message (days)", (date(1917, 4, 2) - date(1917, 3, 1)).days, 32)
eq("war message to declaration (days)", (date(1917, 4, 6) - date(1917, 4, 2)).days, 4)
eq("pledge held until announcement (days)", (date(1917, 1, 31) - date(1916, 5, 4)).days, 272)
eq("ships sunk Feb to April", 10, 10)
# Exports: 824.8 million (1913) to 2.25 billion (1917) -> factor 2.7
between("export growth", 2250 / 824.8, 2.7, 2.75)
# Congress vote: House 373-50 (423); Senate 82-6 (88)
eq("House total", 373 + 50, 423)
eq("Senate total", 82 + 6, 88)
between("House share for", 373 / 423 * 100, 88, 88.4)
# Deaths WWI US: 53,402 battle + 63,114 other = 116,516
eq("US WWI dead", 53402 + 63114, 116516)
# Armistice: 11 November 1918; Meuse-Argonne 26 September: 46 days
eq("Meuse-Argonne days", (date(1918, 11, 11) - date(1918, 9, 26)).days, 46)
# Treaty rejections: 19 November 1919 and 19 March 1920
eq("rejections apart (days)", (date(1920, 3, 19) - date(1919, 11, 19)).days, 121)
# Acquisitions table: nine places
places = ["Hawaii", "Puerto Rico", "Guam", "Philippines", "Wake Island", "American Samoa", "Cuba", "Panama Canal Zone", "Virgin Islands"]
eq("places", len(places), 9)
# Cuba occupation 1898-1902 and Platt lasts to 1934: 33 years from 1901
eq("Platt years", 1934 - 1901, 33)
# Paper totals
eq("paper 1 totals", 15 + 25, 40)
eq("paper 2 totals", (10 + 20) * 2, 60)
# Figure layout (viewBox 340 x 534, generated by data/p14_empire4_fig.py): two stacked panels 320 wide at x=10, four boxes 296 wide, 46 high, 8 apart
BOXH, GAP, TOP, BOT = 46, 8, 30, 14
ph = TOP + 4 * BOXH + 3 * GAP + BOT
eq("panel height", ph, 252)
eq("viewBox height", 10 + 2 * (ph + 10), 534)
for s in ["Philippines and Guam", "Treaty of Paris, Dec 1898", "bought from Denmark, 1917", "treaty of November 1903", "Caribbean and Central America"]:
    assert len(s) * 7 <= 296 - 24, s  # 7 px a character, 12 px side margins inside the box
assert 22 + 296 + 12 == 330 and 10 + 320 + 10 == 340

