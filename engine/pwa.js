// pwa.js — the installable web app, added to the full site by build.js (course kit previews do not get it):
//   manifest.webmanifest, sw.js (offline cache), icons (icons.js) and the <head> tags (<!--HEAD--> in shell.html).
// Every URL is relative, so the site works at any path (GitHub Pages serves it under /<repo>/) and from file://.
'use strict';
const crypto = require('crypto');
const { icons } = require('./icons');

/** --sheet and --red from style.css, light (:root) and dark ([data-theme="dark"]) */
function tokens(css) {
  const block = (sel) => { const i = css.indexOf(sel + ' {'); return i < 0 ? '' : css.slice(i, css.indexOf('}', i)); };
  const get = (b, name) => (b.match(new RegExp(`--${name}:\\s*(#[0-9A-Fa-f]{6})`)) || [])[1];
  const light = block(':root'), dark = block(':root[data-theme="dark"]');
  const t = { sheet: get(light, 'sheet'), red: get(light, 'red'), darkSheet: get(dark, 'sheet') };
  for (const [k, v] of Object.entries(t)) if (!v) throw new Error(`pwa.js: no ${k} colour found in style.css`);
  return t;
}

/** <head> tags, plus the manifest link and service-worker registration (only on http/https; file:// pages skip them) */
function head(css) {
  const t = tokens(css);
  return `<meta name="description" content="A free A Level study guide from zero to A*: every chapter, worked example and practice question works offline.">
<meta name="theme-color" content="${t.sheet}" media="(prefers-color-scheme: light)">
<meta name="theme-color" content="${t.darkSheet}" media="(prefers-color-scheme: dark)">
<meta name="mobile-web-app-capable" content="yes">
<meta name="apple-mobile-web-app-capable" content="yes">
<meta name="apple-mobile-web-app-status-bar-style" content="default">
<meta name="apple-mobile-web-app-title" content="Zero to A*">
<link rel="icon" href="favicon.svg" type="image/svg+xml">
<link rel="icon" href="favicon-32.png" type="image/png" sizes="32x32">
<link rel="apple-touch-icon" href="apple-touch-icon.png">
<script>
(function () {
  // the theme button sets data-theme: the browser and status bars follow it, not only the system setting
  var root = document.documentElement, metas = document.querySelectorAll('meta[name="theme-color"]');
  function bars() {
    var t = root.getAttribute('data-theme');
    for (var i = 0; i < metas.length; i++) metas[i].content = t === 'dark' ? '${t.darkSheet}' : t === 'light' ? '${t.sheet}' : i ? '${t.darkSheet}' : '${t.sheet}';
  }
  if (window.MutationObserver) new MutationObserver(bars).observe(root, { attributes: true, attributeFilter: ['data-theme'] });
  // web app only on http(s): from file:// the manifest is a blocked request and service workers do not exist
  if (!/^https?:$/.test(location.protocol)) return;
  var link = document.createElement('link');
  link.rel = 'manifest'; link.href = 'manifest.webmanifest';
  document.head.appendChild(link);
  if ('serviceWorker' in navigator) addEventListener('load', function () { navigator.serviceWorker.register('sw.js').catch(function () {}); });
})();
</script>`;
}

function manifest(t) {
  return JSON.stringify({
    id: './',
    name: 'Zero to A*',
    short_name: 'Zero to A*',
    description: 'A free A Level study guide from zero to A*, for Cambridge International syllabuses. Works offline.',
    lang: 'en-GB',
    dir: 'ltr',
    start_url: './',
    scope: './',
    display: 'standalone',
    background_color: t.sheet,
    theme_color: t.sheet,
    categories: ['education'],
    icons: [
      { src: 'icon-192.png', sizes: '192x192', type: 'image/png', purpose: 'any' },
      { src: 'icon-512.png', sizes: '512x512', type: 'image/png', purpose: 'any' },
      { src: 'icon-maskable-512.png', sizes: '512x512', type: 'image/png', purpose: 'maskable' }
    ]
  }, null, 2) + '\n';
}

// The service worker. Pages: network first (fresh when online, the last complete copy when offline or after
// WAIT ms on a slow line); a new build has a new cache name, which is filled whole on install, then old caches go.
const SW = (version, files) => `// Zero to A* service worker (generated by engine/pwa.js; do not edit)
'use strict';
const CACHE = ${JSON.stringify(version)};
const FILES = ${JSON.stringify(files)};
const WAIT = 4000;

self.addEventListener('install', (e) => {
  // cache: 'reload' skips the HTTP cache, so the copy is one build, not a mix
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES.map((f) => new Request(f, { cache: 'reload' })))).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (e) => {
  e.waitUntil(caches.keys().then((keys) => Promise.all(keys.filter((k) => k.startsWith('zta-') && k !== CACHE).map((k) => caches.delete(k))))
    .then(() => self.clients.claim()));
});

self.addEventListener('fetch', (e) => {
  const req = e.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  const scope = new URL(self.registration.scope);
  if (url.origin !== scope.origin || !url.pathname.startsWith(scope.pathname)) return;
  // the guide is one page, index.html (chapters are #hash routes); the folder URL is the same page
  const key = url.pathname === scope.pathname ? new URL('index.html', scope).href : url.origin + url.pathname;
  e.respondWith(caches.open(CACHE).then((cache) => {
    const net = fetch(req).then((res) => {
      if (res.ok && res.type === 'basic') cache.put(key, res.clone()).catch(() => {});
      return res;
    });
    const fallback = () => cache.match(key).then((hit) => hit || net);
    return new Promise((resolve) => {
      const t = setTimeout(() => cache.match(key).then((hit) => { if (hit) resolve(hit); }), WAIT);
      net.then((res) => { clearTimeout(t); resolve(res.ok ? res : fallback()); }, () => { clearTimeout(t); resolve(fallback()); });
    });
  }));
});
`;

/**
 * The PWA files for a built site: files = { relPath: content } from site.buildSite (index.html, c/<course>.js).
 * Returns the files to add: manifest, icons and sw.js, whose cache name is a hash of everything it caches.
 */
function pwaFiles(files, css) {
  const t = tokens(css);
  const out = { 'manifest.webmanifest': manifest(t), ...icons(t.red, t.sheet) };
  const all = { ...files, ...out };
  const list = Object.keys(all).sort((a, b) => (a === 'index.html' ? -1 : b === 'index.html' ? 1 : a < b ? -1 : 1));
  const h = crypto.createHash('sha256');
  for (const f of list) h.update(f + '\0').update(all[f]);
  out['sw.js'] = SW('zta-' + h.digest('hex').slice(0, 12), list);
  return out;
}

module.exports = { head, pwaFiles, tokens };
